// Disposable headless visual QA; never reads the Electron autosave profile.
import { chromium } from '/Users/joe/.npm/_npx/e41f203b7505f1fb/node_modules/playwright/index.mjs'
const browser = await chromium.launch({ headless: true, executablePath: '/Users/joe/Library/Caches/ms-playwright/chromium-1234/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing' })
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 1050 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.BLOX_PREVIEW_URL??'http://127.0.0.1:5178')
  await page.getByRole('button', { name: 'Create Project', exact: true }).waitFor()
  await page.evaluate(async () => {
    const { useStore } = await import('/src/store/useStore.ts')
    const s = useStore.getState()
    s.createProject('Willow House · Ground floor', 'quarter')
    const add = (id, x, y, w, h) => { s.placeElement(id, x, y, w, h); return useStore.getState().project.elements.at(-1) }
    const top = add('wall-exterior', 0, 0, 36, .5)
    add('wall-exterior', 0, 25.5, 36, .5)
    add('wall-exterior', 0, 0, .5, 26)
    add('wall-exterior', 35.5, 0, .5, 26)
    const divider = add('wall-interior', 22, .5, .375, 25)
    add('wall-interior', 22.375, 13, 13.125, .375)
    s.placeElement('cased-opening', 22, 16, .375, 3, divider.id)
    s.placeElement('window-double', 6, 0, 5, .5, top.id)
    s.placeElement('window-double', 26, 0, 5, .5, top.id)
    add('furniture-sofa', 3, 8, 7, 2.833)
    add('furniture-coffee-table', 4, 12, 4, 2)
    add('furniture-dining-table', 12, 6, 6, 3)
    add('furniture-bed-queen', 26, 3, 5, 6.667)
    add('fixture-toilet', 31, 17, 1.5, 2.5)
    add('fixture-bathtub', 25, 18, 2.5, 5)
    add('casework-base', 2, 20, 10, 2)
    for (const [text, x, y] of [['LIVING / DINING', 8, 16], ['BEDROOM', 26, 10], ['BATH', 28, 23]]) {
      const note = add('text-note', x, y, 7, 1)
      if (note) s.updateElement(note.id, { properties: { text, fontSize: 11 } })
    }
    s.setStageTransform(140, 105, 1)
    s.clearSelection()
    useStore.setState({ isDirty: false })
  })
  await page.evaluate(() => document.fonts.ready)
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await page.evaluate(async () => {
    const { useStore } = await import('/src/store/useStore.ts')
    useStore.getState().setStageTransform(140, 105, 1)
  })
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  await page.screenshot({ path: 'artifacts/workspace-modern.png' })
  await page.getByLabel('Category', { exact: true }).selectOption('Furniture')
  await page.screenshot({ path: 'artifacts/workspace-furniture.png' })
  for (const category of ['Fixtures', 'Casework']) {
    await page.getByLabel('Category', { exact: true }).selectOption(category)
    if (await page.locator('.blox-card').count() === 0) throw new Error(`Missing ${category} previews`)
    await page.screenshot({ path: `artifacts/workspace-${category.toLowerCase()}.png` })
  }
  await page.getByRole('button', { name: 'Exterior Wall (W)', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await page.getByRole('button', { name: /Free Angle/ }).waitFor()
  await page.screenshot({ path: 'artifacts/workspace-tool-icons.png' })
  await page.keyboard.press('Escape')
  await page.getByLabel('Category', { exact: true }).selectOption('all')
  await page.evaluate(async () => {
    const { useStore } = await import('/src/store/useStore.ts')
    const s = useStore.getState()
    s.selectElement(s.project.elements.find(e => e.bloxId === 'furniture-sofa').id)
  })
  await page.getByRole('button', { name: 'Rotate 90° (R)', exact: true }).waitFor()
  await page.getByTitle('File menu', { exact: true }).click()
  await page.getByRole('button', { name: 'Open Project', exact: true }).waitFor()
  await page.screenshot({ path: 'artifacts/workspace-icons.png' })
  await page.getByTitle('File menu', { exact: true }).click()
  const inspector=page.getByRole('region',{name:'Selection properties'})
  await inspector.getByLabel('Width',{exact:true}).fill('8')
  await inspector.getByLabel('Rotation',{exact:true}).fill('15')
  await inspector.getByRole('button',{name:'Flip Horizontal',exact:true}).click()
  await inspector.getByRole('button',{name:'Lock object',exact:true}).click()
  await inspector.getByRole('button',{name:'Unlock object',exact:true}).click()
  await page.evaluate(async()=>{
    const {useStore}=await import('/src/store/useStore.ts')
    const sofa=useStore.getState().project.elements.find(e=>e.bloxId==='furniture-sofa')
    if(sofa.width!==8||sofa.rotation!==15||!sofa.properties.flipH||sofa.locked) throw new Error('Inspector controls failed')
    useStore.getState().updateElement(sofa.id,{width:7,rotation:0,properties:{...sofa.properties,flipH:false}})
  })
  await page.getByLabel('Category',{exact:true}).selectOption('Furniture')
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
  await page.screenshot({path:'artifacts/workspace-inspector.png'})
  await page.setViewportSize({width:1000,height:850})
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
  await page.screenshot({path:'artifacts/workspace-inspector-compact.png'})
  if(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)) throw new Error('Inspector layout overflows viewport')
  await page.setViewportSize({width:1600,height:1050})
  await page.evaluate(async () => { const { useStore } = await import('/src/store/useStore.ts'); useStore.getState().clearSelection() })
  await page.getByLabel('Category', { exact: true }).selectOption('Openings')
  if (await page.locator('.library-category').count() !== 1) throw new Error('Category filter failed')
  await page.locator('.library-category').click()
  if (await page.locator('.blox-card').count() !== 0) throw new Error('Category collapse failed')
  await page.locator('.library-category').click()
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await page.getByRole('button', { name: 'Zoom options', exact: true }).click()
  await page.getByRole('button', { name: '100%', exact: true }).click()
  await page.screenshot({ path: 'artifacts/workspace-categories.png' })
  await page.getByLabel('Category', { exact: true }).selectOption('all')
  await page.getByRole('textbox', { name: 'Search blox', exact: true }).fill('door')
  await page.getByRole('button', { name: /Single Door/ }).click()
  await page.screenshot({ path: 'artifacts/workspace-library.png' })
  await page.evaluate(async () => {
    const { useStore } = await import('/src/store/useStore.ts')
    useStore.getState().setActiveBlox(null)
    useStore.setState({ showDRCPanel: true })
    useStore.getState().setStageTransform(60, 100, .75)
  })
  await page.locator('.review-panel').waitFor()
  await page.screenshot({ path: 'artifacts/workspace-review.png' })
  await page.evaluate(async () => {
    const { useStore } = await import('/src/store/useStore.ts')
    useStore.setState({ showDRCPanel: false, showNewProjectDialog: true })
  })
  await page.getByRole('dialog').waitFor()
  await page.screenshot({ path: 'artifacts/workspace-new-project.png' })
  console.log(JSON.stringify({ errors, cards: await page.locator('.blox-card').count() }))
  if (errors.length) process.exitCode = 1
} finally { await browser.close() }
