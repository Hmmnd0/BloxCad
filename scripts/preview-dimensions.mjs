import { chromium } from '/Users/joe/.npm/_npx/e41f203b7505f1fb/node_modules/playwright/index.mjs'
const browser=await chromium.launch({headless:true,executablePath:'/Users/joe/Library/Caches/ms-playwright/chromium-1234/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing'})
try {
  const page=await browser.newPage({viewport:{width:1600,height:1050}})
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto(process.env.BLOX_PREVIEW_URL??'http://127.0.0.1:5178')
  await page.getByRole('button',{name:'Create Project',exact:true}).waitFor()
  await page.evaluate(async()=>{
    const {useStore}=await import('/src/store/useStore.ts')
    const s=useStore.getState();s.createProject('Linked foundation dimensions','quarter')
    for(const [x,y,w,h] of [[0,0,28,2],[0,20,28,2],[0,0,2,22],[26,0,2,22]]) s.placeElement('wall-cmu-footing',x,y,w,h)
    s.autoDimSelected('up');s.autoDimSelected('left')
    s.addDimension({x1:1.4,y1:1.4,x2:26.6,y2:1.4,offset:-2,measurement:'horizontal'})
    s.addDimension({x1:6,y1:7,x2:9,y2:11,offset:1.5,measurement:'aligned'})
    const current=useStore.getState();s.selectMany([], [current.project.dimensions.at(-1).id])
  })
  const frame=()=>page.evaluate(()=>new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))))
  await frame()
  await page.screenshot({path:'artifacts/dimensions-initial-check.png'})
  if(errors.length) throw new Error(errors.join('\n'))
  await page.evaluate(async()=>{const {useStore}=await import('/src/store/useStore.ts');useStore.getState().setStageTransform(140,120,1)})
  await frame()
  await page.getByLabel('Dimension measurement').selectOption('horizontal')
  await page.getByLabel('Dimension measurement').selectOption('aligned')
  const initial=await page.evaluate(async()=>{
    const {useStore,getActiveDimensions}=await import('/src/store/useStore.ts')
    const {dimensionLayout}=await import('/src/utils/dimensionLayout.ts')
    const ds=getActiveDimensions(useStore.getState())
    if(!ds[2].anchor1||!ds[2].anchor2) throw new Error('Inner stem corners did not attach')
    if(dimensionLayout(ds[3],1).value!==5) throw new Error('Aligned measurement mismatch')
    return ds.map(d=>({value:dimensionLayout(d,1).value,x1:d.x1,y1:d.y1}))
  })
  await page.screenshot({path:'artifacts/dimensions-linked.png'})
  const moved=await page.evaluate(async()=>{
    const {useStore,getActiveDimensions}=await import('/src/store/useStore.ts')
    const s=useStore.getState();s.moveElements(s.project.elements.map(w=>({id:w.id,x:w.x+2,y:w.y+1})))
    const ds=getActiveDimensions(useStore.getState())
    if(ds[0].x1!==2||ds[0].y1!==1||ds[2].needsReview||Math.abs(ds[2].x1-3.4)>1e-6) throw new Error('Dimensions failed to follow foundation')
    const {buildProjectSVG}=await import('/src/utils/svgExport.ts')
    const svg=buildProjectSVG(useStore.getState().project)
    if(!svg.includes('5\'')||svg.includes('CHECK')) throw new Error('SVG measurement mismatch')
    return {x1:ds[0].x1,y1:ds[0].y1}
  })
  await frame();await page.screenshot({path:'artifacts/dimensions-moved.png'})
  await page.evaluate(async()=>{
    const {useStore,getActiveDimensions}=await import('/src/store/useStore.ts')
    const s=useStore.getState();s.undo()
    if(getActiveDimensions(useStore.getState())[0].x1!==0) throw new Error('Undo did not restore dimension')
    const d=getActiveDimensions(useStore.getState())[2]
    const id=d.anchor1.faces[0].wallId
    s.selectMany([id]);s.deleteSelectedElements();s.selectMany([],[d.id])
    if(!getActiveDimensions(useStore.getState()).find(x=>x.id===d.id).needsReview) throw new Error('Missing reference not marked')
    const {buildProjectSVG}=await import('/src/utils/svgExport.ts')
    if(!buildProjectSVG(useStore.getState().project).includes('CHECK')) throw new Error('Export omitted reference warning')
  })
  await page.getByText('CHECK — reference changed',{exact:true}).waitFor()
  await frame();await page.screenshot({path:'artifacts/dimensions-check.png'})
  if(errors.length) throw new Error(errors.join('\n'))
  console.log(JSON.stringify({initial,moved,errors}))
} finally {await browser.close()}
